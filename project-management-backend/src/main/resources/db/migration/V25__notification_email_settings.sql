-- Email-уведомления (4.3 IMPROVEMENTS.md).
--
-- До этой миграции уведомление существовало ровно в одном месте — в колокольчике. Человек,
-- не открывший вкладку, о назначенной задаче или горящем дедлайне не узнавал вовсе, а
-- MailService умел единственный тип письма (верификацию). Здесь появляется вторая доставка
-- тех же четырёх типов (task_assigned / task_comment / task_due_soon / task_overdue) — почтой,
-- и настройки, которыми человек управляет тем, что и как ему шлют.

-- Настройки уведомлений пользователя. Строка НЕ создаётся при регистрации: её отсутствие
-- означает «всё по умолчанию» (см. NotificationSettingsService.DEFAULTS), и появляется она
-- только когда человек что-то поменял или отписался. Иначе пришлось бы либо трогать
-- регистрацию, либо мириться с тем, что у старых пользователей строки нет, — то есть всё
-- равно писать ветку «настроек нет».
CREATE TABLE notification_settings (
    user_id UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    -- Главный выключатель, он же то, что дёргает ссылка «отписаться» из письма. Отдельный
    -- от типов ниже сознательно: отписка не должна стирать настройку «какие типы мне важны»,
    -- иначе вернуться к прежнему состоянию человек уже не сможет — только настроить заново.
    email_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    -- INSTANT — письмо на каждое событие, DAILY_DIGEST — одно письмо в сутки сводкой
    -- (NotificationDigestJob). Значения совпадают с NotificationDeliveryMode; CHECK здесь
    -- не про удобство, а про то, что enum на стороне приложения ничего не гарантирует базе.
    mode VARCHAR(16) NOT NULL DEFAULT 'INSTANT' CHECK (mode IN ('INSTANT', 'DAILY_DIGEST')),
    -- По колонке на тип, а не JSONB и не строка со списком: типов ровно четыре, они заданы
    -- кодом (NotificationService.TYPE_*), и запрос «кому слать про комментарии» должен быть
    -- обычным условием, а не разбором документа.
    task_assigned BOOLEAN NOT NULL DEFAULT TRUE,
    task_comment BOOLEAN NOT NULL DEFAULT TRUE,
    task_due_soon BOOLEAN NOT NULL DEFAULT TRUE,
    task_overdue BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- «Письмо по этому уведомлению уже ушло (или уже уехало в отправку)». NULL — не уходило.
--
-- Колонка нужна именно из-за дайджеста: он собирает то, о чём человеку ещё не писали, и без
-- отметки либо повторял бы вчерашнее, либо терял бы всё за сутки, в которые джоб не отработал.
-- Мгновенная доставка ставит отметку в той же транзакции, что создаёт уведомление, — то есть
-- «отправлено» здесь означает «передано MailDispatcher», а не «доставлено получателю»:
-- ретраи и судьба письма дальше — его дело, и повторять их вечером дайджестом незачем.
--
-- У выключенного типа отметка не ставится вовсе: письма не было и не будет, а трогать
-- колонку с именем email_sent_at ради «решили не слать» значило бы врать её названием.
ALTER TABLE notifications ADD COLUMN email_sent_at TIMESTAMPTZ;

-- Выборка дайджеста: «что у этого получателя ещё не уехало письмом». Частичный индекс, как
-- и у непрочитанных: строки с проставленным email_sent_at (то есть подавляющее большинство
-- при мгновенной доставке — режиме по умолчанию) в него не попадают вообще.
CREATE INDEX idx_notifications_pending_email
    ON notifications (recipient_id, created_at)
    WHERE email_sent_at IS NULL;
