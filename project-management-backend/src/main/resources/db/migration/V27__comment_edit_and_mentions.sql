-- Редактирование комментариев (4.4) и @упоминания в них (4.5 IMPROVEMENTS.md).
--
-- До сих пор комментарий был неизменяемым: и колонка body, и вся сущность TaskComment
-- объявлены updatable = false. Исправить опечатку можно было только удалив комментарий и
-- написав заново — с потерей места в треде и с «удалил и написал то же самое» в ленте.

-- Отметка правки. NULL — «не редактировали ни разу», и это не пробел в данных, а
-- содержательное состояние: интерфейс показывает пометку «изменено» ровно тогда, когда
-- значение есть. Отдельная колонка, а не updated_at со значением по умолчанию = created_at:
-- «создан и с тех пор не тронут» и «создан, потом отредактирован в ту же секунду» должны
-- различаться, а при equals-сравнении двух timestamptz они бы слились.
--
-- Истории версий нет намеренно: она нужна там, где по комментарию принимают решения и
-- спорят о формулировках, — здесь же цена (таблица ревизий, её показ, её чистка) заметно
-- выше пользы от «а что было написано раньше». Модерация чужого комментария осталась
-- удалением: править чужие слова не может никто, включая OWNER (см. NotCommentAuthorException).
ALTER TABLE task_comments ADD COLUMN edited_at TIMESTAMPTZ;

-- Пятый тип уведомления — task_mention («вас упомянули»). Колонка, как и четыре соседние
-- (см. V25): типы заданы кодом, их по-прежнему немного, и «кому слать про упоминания»
-- должно быть обычным условием запроса.
--
-- DEFAULT TRUE и для уже существующих строк: упоминание — это адресное обращение к
-- человеку, и умолчание «не писать» означало бы, что позвали, а он не узнал. Тот, кто
-- ранее выключил себе task_comment, упоминания получать продолжит — это разные вещи:
-- «в треде моей задачи опять пишут» и «меня позвали по имени».
ALTER TABLE notification_settings ADD COLUMN task_mention BOOLEAN NOT NULL DEFAULT TRUE;

-- Отдельной таблицы упоминаний нет. Единственный источник правды о том, кто упомянут, —
-- сам текст комментария: он же показывается, он же редактируется, и вторая копия этого
-- знания рядом означала бы только возможность разъехаться с текстом. Всё, ради чего таблицу
-- обычно заводят, решается без неё: «не уведомить повторно при правке» вычисляется из
-- старого и нового тела в той же транзакции (TaskCommentService.update), а «покажи, где
-- меня упоминали» — это поиск, и он уже полнотекстовый (V23; search_vector у task_comments
-- генерируемый, поэтому правка тела переиндексируется сама, без единой строчки кода).
