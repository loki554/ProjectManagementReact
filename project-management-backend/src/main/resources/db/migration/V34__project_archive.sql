-- Архивация проектов (4.14).
--
-- Колонка projects.archived существует с V2, но до сих пор ничего не делала: её ставили
-- галочкой в форме настроек, и она рисовала серый бейдж на карточке. Проект при этом
-- оставался в списке, в «моих задачах» и в напоминаниях о сроках — то есть архив не
-- отвечал на единственный вопрос, ради которого он нужен: «уберите с глаз то, что уже
-- закончено, но не давайте это потерять».
--
-- Данных миграция почти не добавляет — она добавляет дату. Флага мало для списка архива:
-- «когда закончили» — первое, по чему такой список сортируют и по чему в нём узнают
-- нужную строку, а updated_at для этого не годится: его двигает любая правка.
ALTER TABLE projects
    ADD COLUMN archived_at TIMESTAMPTZ;

-- Уже заархивированным проектам (если такие есть — галочка существовала и ею могли
-- пользоваться) проставляем момент последней правки: точной даты архивации в схеме не
-- было, а updated_at — единственное, что к ней хоть как-то близко. Лучше приблизительная
-- дата, чем пустая колонка, которую интерфейсу пришлось бы уметь показывать особым образом.
UPDATE projects SET archived_at = updated_at WHERE archived = TRUE;

-- Индекса под "archived = false" здесь нет намеренно. Список проектов всегда идёт от
-- участника (project_members.user_id → projects), и отбирается по нему не таблица
-- проектов, а десятки строк одного человека; фильтр по архиву применяется уже к ним.
-- Индекс на колонку, у которой два значения, в таком запросе не будет выбран планировщиком.
