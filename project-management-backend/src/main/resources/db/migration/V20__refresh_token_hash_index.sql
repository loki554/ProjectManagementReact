-- Индекс под поиск refresh-токена по хешу.
--
-- AuthService.refresh и AuthService.logout ищут строку через findByTokenHash, а в V1 индекса
-- на token_hash не было — только на user_id. То есть каждое обновление сессии (а оно
-- происходит при каждой перезагрузке страницы у каждого пользователя и дальше раз в 15 минут,
-- пока вкладка открыта) шло полным сканом таблицы, которая растёт с каждым логином.
-- TokenCleanupJob удаляет истёкшие строки только через 30 дней после протухания (грейс-период
-- нужен детекту повторного использования), поэтому даже с чисткой таблица постоянно держит
-- месячный объём всех сессий сервиса.
--
-- UNIQUE, а не обычный индекс: token_hash — это SHA-256 от 64 случайных байт, коллизия
-- невозможна практически, но если она (или, что реальнее, ошибка в коде выдачи токенов)
-- всё же случится, два пользователя получат один ключ к сессии. Пусть в этом случае падает
-- INSERT, а не молча срабатывает findByTokenHash на чужой строке. Заодно это позволяет
-- Postgres знать, что по хешу всегда не больше одной строки.
--
-- В password_reset_tokens (V19) и email_verification_tokens (V1) UNIQUE на токене уже есть —
-- индекс там создаётся автоматически вместе с ограничением, отдельная строка не нужна.
CREATE UNIQUE INDEX idx_refresh_tokens_token_hash ON refresh_tokens(token_hash);
