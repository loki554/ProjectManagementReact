-- Отчёты по времени (4.10) и дашборд проекта (4.11).
--
-- Миграция состоит из одних индексов, и это главное, что стоит про эти два пункта знать:
-- новых данных они не заводят. Часы уже лежат в time_logs с V4, переходы статусов — в
-- project_activity с V13, состав спринта — в tasks.sprint_id с V31. Оба экрана только
-- читают то, что трекер и так копил, и ровно поэтому их стоило сделать: сбор данных уже
-- оплачен, не оплачен был ответ на вопрос «и что?».
--
-- Единственное, чего не хватало, — индексов под эти два новых паттерна чтения. Оба
-- запроса раньше не существовали, поэтому и индексов под них не было.

-- Отчёт по времени фильтрует по периоду («часы за сентябрь»), и это его главный фильтр:
-- проект отсекается join'ом с tasks (там есть idx_tasks_project_id_status), а период —
-- ничем. Без индекса каждый отчёт читает time_logs целиком.
--
-- Индекс по одному spent_on, а не по (project_id, spent_on): project_id в time_logs нет.
-- Он есть у задачи, и денормализовать его сюда ради отчёта было бы дорого — колонка,
-- которую надо поддерживать в согласии с task_id, ради запроса, который выполняется
-- несколько раз в день. Когда одного spent_on перестанет хватать (то есть когда записей
-- времени станет столько, что период перестанет быть селективным), правильным следующим
-- шагом будет именно денормализация, а не второй индекс.
CREATE INDEX idx_time_logs_spent_on ON time_logs(spent_on);

-- Дашборд читает историю статусов: burndown восстанавливает по ней, что было закрыто на
-- каждый день спринта, а «среднее время в статусе» — сколько задача пролежала в каждом.
-- Оба запроса берут из ленты активности одну её узкую полосу — события task_status_changed
-- по конкретным задачам, — а существующие индексы ленты заточены под другое: и
-- (project_id, created_at DESC) из V13, и (task_id, created_at) из V15 отвечают на вопрос
-- «покажи последние события», где тип события не важен вовсе.
--
-- Индекс частичный: task_status_changed — заметно меньшая часть ленты, чем всё остальное
-- вместе (комментарии, вложения, правки полей), и держать в индексе строки, по которым
-- дашборд никогда не пойдёт, незачем. Условие WHERE в запросах дашборда выписано ровно в
-- этом же виде (type = 'task_status_changed'), иначе планировщик частичный индекс не
-- возьмёт.
CREATE INDEX idx_project_activity_status_changes
    ON project_activity (project_id, task_id, created_at)
    WHERE type = 'task_status_changed';
