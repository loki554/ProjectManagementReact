-- Горизонтальные связи между задачами (4.8): «эта задача блокирует ту». Иерархия
-- parent/subtask в схеме была с V3, но она про состав («из чего задача состоит»), а не про
-- очерёдность («что должно случиться раньше»): подзадачу нельзя объявить блокером соседней
-- задачи, не сделав её частью этой задачи, а перекладывать порядок работ в иерархию — это
-- как раз то, из-за чего в трекерах заводят отдельный тип связи.
--
-- Одна строка = одно ребро «blocker должен закрыться раньше, чем blocked». Обратная связь
-- («блокирует») — та же строка, прочитанная с другого конца: хранить её вторым рядом
-- значило бы завести две записи об одном факте и получить возможность разъехаться.
-- Поэтому тип связи в таблице не хранится: он один-единственный, и колонка вроде
-- link_type = 'BLOCKS' была бы колонкой с одним значением. Появятся «дублирует» и
-- «связана с» — они добавятся именно ей, потому что у них другая семантика (симметричная,
-- без влияния на статус), и заводить их сейчас нечем: в пункте 4.8 их нет.
--
-- Проекта в таблице нет намеренно, хотя запросы фильтруют по нему. Он выводится из любой
-- из двух задач, а «оба конца в одном проекте» — правило приложения (см. TaskDependencyService),
-- и колонка project_id здесь была бы третьим местом, где хранится то же самое, с
-- обязанностью его синхронизировать. Задача, к слову, из проекта не переезжает: project_id
-- у неё updatable = false.

CREATE TABLE task_dependencies (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- ON DELETE CASCADE с обеих сторон: физическое удаление задачи (чистка корзины,
    -- TaskCleanupJob) уносит и все её связи. Мягкое удаление (3.5) строки не трогает —
    -- задача в корзине восстановима, и восстановиться она должна вместе со своими
    -- зависимостями; из подсчёта «незакрытых блокеров» она при этом выпадает, потому что
    -- любой запрос через сущность Task наталкивается на её @SQLRestriction.
    blocker_task_id UUID NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    blocked_task_id UUID NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,

    -- Кто связал. Нужен ленте активности и разбору «откуда это взялось»; ON DELETE SET NULL,
    -- как и у actor_id в project_activity: связь переживает удаление аккаунта её автора.
    created_by UUID REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Задача, блокирующая сама себя, — это задача, которую нельзя закрыть никогда. Проверка
    -- дублирует явный отказ в сервисе (400 SELF_DEPENDENCY, чтобы человек увидел причину, а
    -- не «конфликт данных»), но остаётся в схеме: сюда ходят и миграции, и psql.
    CONSTRAINT chk_task_dependencies_not_self CHECK (blocker_task_id <> blocked_task_id),

    -- Одна и та же связь дважды — это не «сильнее блокирует», а дубль в списке и лишняя
    -- строка при подсчёте. Порядок колонок в ключе — под основной запрос («кто блокирует
    -- эту задачу»), см. индекс ниже.
    CONSTRAINT uq_task_dependencies UNIQUE (blocked_task_id, blocker_task_id)
);

-- Уникальный ключ выше обслуживает своим префиксом чтение «кто блокирует задачу X» и
-- проверку «не закрыта ли она». Обратное направление («кого блокирует X») — отдельный
-- запрос: он нужен и панели зависимостей на странице задачи, и обходу графа при поиске
-- цикла, а префикса под него в уникальном ключе нет.
CREATE INDEX idx_task_dependencies_blocker ON task_dependencies (blocker_task_id);
