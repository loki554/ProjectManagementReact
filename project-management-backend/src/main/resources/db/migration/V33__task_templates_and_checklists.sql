-- Шаблоны задач и чек-листы (4.13). Один пункт, но две таблицы данных и одна связующая,
-- потому что за повторяющейся работой стоят две разные жалобы. Первая: «каждый релиз я
-- завожу одну и ту же задачу с одним и тем же описанием» — это шаблон. Вторая: «внутри
-- задачи семь шагов, и я забываю, какие уже сделал» — это чек-лист. Их стоит делать
-- вместе, потому что ценность шаблона почти целиком в списке шагов, который он приносит с
-- собой: без чек-листа шаблон копирует три поля формы, ради которых никто не пойдёт
-- заводить шаблон.

-- ------------------------------------------------------------------ чек-лист задачи

-- Пункт чек-листа — это НЕ подзадача, и различие здесь не косметическое. У подзадачи есть
-- номер, исполнитель, статус, срок, своя карточка на доске и своё место в отчётах; она
-- существует, чтобы её кому-то поручить. Пункт чек-листа не существует отдельно от задачи:
-- это строка «сделано / не сделано» внутри одной чужой работы, и заводят её тот же человек
-- и в ту же минуту, когда пишут описание. Попытка обойтись подзадачами уже проверена
-- практикой других трекеров: доска зарастает карточками «проверить логи», а счётчик задач
-- проекта перестаёт что-либо значить.
CREATE TABLE task_checklist_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- ON DELETE CASCADE: пункт вне задачи не значит ничего. Мягкое удаление (V22) сюда не
    -- добирается и не должно: задача уезжает в корзину целиком вместе со своим чек-листом
    -- и возвращается из неё в том же виде.
    task_id UUID NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,

    -- VARCHAR(500), а не TEXT: пункт чек-листа — это строка «обновить changelog», которую
    -- видно целиком в один взгляд. Всё, что не влезает в пятьсот символов, — это описание
    -- задачи или отдельная задача, а не галочка.
    content VARCHAR(500) NOT NULL,

    done BOOLEAN NOT NULL DEFAULT FALSE,

    -- Порядок пунктов — это порядок шагов, и он несёт смысл («сначала собрать, потом
    -- выкатить»). Хранится явно, а не выводится из created_at: пункт, дописанный в
    -- середину, обязан там и остаться.
    position INT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Кто и когда поставил галочку, здесь не хранится сознательно. Чек-лист — это текущее
-- состояние задачи, а не журнал: «кто что сделал» в трекере уже отвечают лента активности
-- и комментарии, и заводить третий, неполный ответ на тот же вопрос (галочку ведь ещё и
-- снимают) значило бы платить двумя колонками за строку, которую негде показать.

-- Читают чек-лист всегда целиком и всегда по одной задаче, сразу в нужном порядке.
CREATE INDEX idx_task_checklist_items_task_id ON task_checklist_items(task_id, position);

-- ------------------------------------------------------------------ шаблоны задач

-- Шаблон — это заготовка формы задачи, а не задача. Отдельная таблица, а не «задача с
-- флагом is_template»: у шаблона нет ни номера, ни статуса, ни исполнителя, ни срока, и
-- флаг на tasks означал бы, что каждый запрос трекера — доска, список, поиск, счётчики
-- спринта, выгрузка — обязан не забыть про него отфильтроваться. Ровно та ошибка, от
-- которой в V22 спасает @SQLRestriction, только на этот раз добровольная.
CREATE TABLE task_templates (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,

    -- Имя шаблона — то, что видно в выпадающем списке при заведении задачи («Релиз»,
    -- «Онбординг»). Это не заголовок будущей задачи: заголовок лежит ниже и вполне может
    -- отличаться («Релиз 2.7» против шаблона «Релиз»).
    name VARCHAR(100) NOT NULL,

    -- Поля будущей задачи. Все необязательные, включая заголовок: шаблон, который приносит
    -- только чек-лист из десяти пунктов, — это законный и, скорее всего, самый частый
    -- шаблон. NULL здесь означает «шаблон про это поле ничего не говорит», и форма оставит
    -- его как есть; пустая строка означала бы «очистить», а очищать в пустой форме нечего.
    title VARCHAR(255),
    description TEXT,
    urgency VARCHAR(20),

    -- ON DELETE SET NULL, как у задачи (V6/V18): удаление тэга или категории не должно
    -- уносить шаблон целиком — оно всего лишь делает его на одно поле беднее.
    tag_id UUID REFERENCES tags(id) ON DELETE SET NULL,
    category_id UUID REFERENCES categories(id) ON DELETE SET NULL,

    created_by UUID NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Имя уникально в проекте — по той же причине, что у тэгов, категорий и спринтов: два
    -- одинаковых пункта в выпадающем списке неразличимы ровно в тот момент, когда из него
    -- выбирают.
    CONSTRAINT uq_task_templates_project_name UNIQUE (project_id, name)
);

CREATE INDEX idx_task_templates_project_id ON task_templates(project_id);

-- Пункты чек-листа шаблона. Отдельная таблица, а не массив строк в колонке шаблона:
-- порядок и текст пунктов правятся по одному, а массив пришлось бы переписывать целиком
-- и разбирать в коде на каждом чтении. Плюс так пункт шаблона и пункт задачи устроены
-- одинаково, и копирование первого во второй — это одна вставка, а не преобразование.
CREATE TABLE task_template_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    template_id UUID NOT NULL REFERENCES task_templates(id) ON DELETE CASCADE,
    content VARCHAR(500) NOT NULL,
    position INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- done здесь нет и быть не может: шаблон — это заготовка, галочку ставят на копии.

CREATE INDEX idx_task_template_items_template_id ON task_template_items(template_id, position);
