-- Никнейм пользователя: публичный идентификатор, по которому человека зовут в комментариях.
--
-- Появился как замена @упоминаниям по почтовому адресу (V27, 4.5): адрес в роли публичного
-- имени плох сразу с двух сторон — читать «@ivanov@example.com» посреди фразы неудобно, а
-- писать чужой почтовый ящик в текст, который увидит весь проект, тем более. Никнейм даёт
-- то же, ради чего адрес и брался (уникальность и разбор упоминания на сервере), не будучи
-- при этом контактными данными.
--
-- Формат — [a-z0-9_-], 3-30 символов, нижний регистр (см. UsernameNormalizer). Точка в набор
-- намеренно не входит: упоминание в тексте кончается на первом символе не из набора, и без
-- точки «зайдите к @ivanov.» разбирается однозначно, а с точкой пришлось бы гадать, где
-- никнейм, а где конец предложения.

-- Колонка сначала nullable: строки уже есть, а значения для них ещё нет.
ALTER TABLE users ADD COLUMN username VARCHAR(30);

-- Индекс до бэкофилла, а не после: он же обслуживает проверку «свободно ли» внутри цикла
-- ниже. NULL-значения уникальности не мешают — в btree их сколько угодно.
CREATE UNIQUE INDEX uq_users_username ON users (username);

-- Бэкофилл существующим пользователям. Никнейм выводится из локальной части адреса — это
-- единственное, что о человеке известно и на что он откликается; ФИО не годится (кириллица),
-- а случайная строка вида user-8f3c означала бы, что при выкате все существующие аккаунты
-- получают имя, которое никто не узнает и каждый пойдёт менять.
--
-- Разбор специально «тупой»: всё, что не входит в разрешённый набор, становится дефисом,
-- повторы схлопываются, края обрезаются. Коллизии (ivan@a.com и ivan@b.com дают один и тот
-- же ivan) разводятся суффиксом -2, -3 и так далее; проверка идёт по уже вставленным
-- строкам, поэтому цикл, а не одиночный UPDATE.
DO $$
DECLARE
    r RECORD;
    base TEXT;
    candidate TEXT;
    suffix INT;
BEGIN
    -- По порядку создания: если два адреса дают одну основу, «ivan» достаётся тому, кто
    -- зарегистрировался раньше, а не тому, кого первым вернул планировщик.
    FOR r IN SELECT id, email FROM users ORDER BY created_at, id LOOP
        base := lower(split_part(r.email, '@', 1));
        base := regexp_replace(base, '[^a-z0-9_-]', '-', 'g');
        base := regexp_replace(base, '-{2,}', '-', 'g');
        base := btrim(base, '-');
        base := left(base, 30);
        -- Адрес целиком из недопустимых символов (или слишком короткий) — дополняем нулями
        -- до минимальной длины. Такой никнейм бессмыслен, но это рабочее значение, которое
        -- человек поменяет в профиле, а не упавшая миграция.
        IF length(base) < 3 THEN
            base := rpad(base, 3, '0');
        END IF;

        candidate := base;
        suffix := 1;
        WHILE EXISTS (SELECT 1 FROM users WHERE username = candidate) LOOP
            suffix := suffix + 1;
            -- Суффикс приписывается вместо хвоста, а не сверх него: колонка 30 символов.
            candidate := left(base, 30 - length(suffix::text) - 1) || '-' || suffix;
        END LOOP;

        UPDATE users SET username = candidate WHERE id = r.id;
    END LOOP;
END $$;

-- Теперь колонка обязательна: никнейм есть у всех и спрашивается при регистрации.
ALTER TABLE users ALTER COLUMN username SET NOT NULL;

-- Формат стережёт БД, а не только валидация DTO. Причина та же, что у V26 с регистром почты:
-- инвариант, на который опирается разбор упоминаний, не должен зависеть от того, что все
-- будущие пути записи про него вспомнят. Никнейм не из этого набора сделал бы упоминание
-- ненаходимым — то есть человека, которого нельзя позвать, и без единой ошибки где-либо.
ALTER TABLE users ADD CONSTRAINT users_username_format CHECK (username ~ '^[a-z0-9_-]{3,30}$');

