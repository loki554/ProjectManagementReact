-- Мягкое удаление задач и корзина проекта (3.5).
--
-- До сих пор DELETE /api/tasks/{id} удалял строку физически, а вместе с ней по
-- ON DELETE CASCADE уезжали подзадачи, комментарии, вложения и всё залогированное время.
-- Подтверждение при этом — обычный window.confirm, то есть одно неверное нажатие
-- уничтожало недели работы без единого способа её вернуть.
--
-- Теперь удаление проставляет deleted_at, а физически строки убирает TaskCleanupJob через
-- 30 дней. Невидимость удалённых задач для остального приложения обеспечивает не фильтр в
-- каждом запросе (их полтора десятка, и забыть один — значит показать удалённую задачу в
-- одном экране из десяти), а @SQLRestriction на самой сущности Task: Hibernate дописывает
-- условие ко всем загрузкам и HQL-запросам сам. Обратная сторона — корзина, восстановление
-- и чистка вынуждены ходить в эту таблицу нативным SQL, мимо ORM; так и сделано.
--
-- Индекс частичный: deleted_at IS NULL у подавляющего большинства строк, и индексировать
-- их незачем — по столбцу ходят ровно два запроса, оба про содержимое корзины.

ALTER TABLE tasks ADD COLUMN deleted_at TIMESTAMPTZ;

CREATE INDEX idx_tasks_deleted_at ON tasks(project_id, deleted_at) WHERE deleted_at IS NOT NULL;
