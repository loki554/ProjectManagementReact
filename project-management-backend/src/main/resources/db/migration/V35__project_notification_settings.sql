-- Настраиваемые уведомления по проектам (4.16 IMPROVEMENTS.md).
--
-- До этой миграции у человека была ровно одна настройка уведомлений на всё приложение
-- (notification_settings, V25) — и она отвечала на вопрос «как вам писать», но не на
-- вопрос «о чём». А вопрос «о чём» на практике задаётся именно проектами: в одном я
-- работаю каждый день, во втором числюсь наблюдателем ради одной страницы вики, а третий
-- ведёт соседняя команда, и меня туда позвали посмотреть один раз в марте. Глобальные
-- переключатели типов тут бессильны: выключить «комментарий к моей задаче» ради третьего
-- проекта значит выключить его и в первом.
--
-- Отсюда вторая, поперечная ось настройки: строка на пару (проект, человек).

CREATE TABLE project_notification_settings (
    -- Суррогатный id + UNIQUE, а не составной первичный ключ, — тот же приём, что у
    -- project_members и project_stars. Составной PK в JPA стоит @IdClass/@EmbeddedId и
    -- отдельного класса ключа; выигрыш при этом чисто эстетический, а разнобой с двумя
    -- соседними таблицами про ту же пару (проект, пользователь) — вполне реальный.
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- ALL           — писать обо всём, что происходит в проекте (новые задачи, все
    --                 комментарии), а не только о том, что касается меня лично;
    -- PARTICIPATING — поведение по умолчанию и до этой миграции: назначения, комментарии
    --                 к моим задачам, упоминания, сроки моих задач;
    -- MUTED         — не писать ничего: ни письмом, ни в колокольчик.
    --
    -- CHECK, как и у notification_settings.mode: enum на стороне приложения базе ничего
    -- не гарантирует, а строка с опечаткой здесь означала бы молчаливо потерянные
    -- уведомления — то есть ровно тот сорт ошибки, который не видно ни в логах, ни в API.
    mode VARCHAR(16) NOT NULL CHECK (mode IN ('ALL', 'PARTICIPATING', 'MUTED')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (project_id, user_id)
);

-- Строка НЕ создаётся при вступлении в проект — ровно по той же причине, по которой её не
-- создаёт регистрация (V25): её отсутствие означает PARTICIPATING, то есть в точности то
-- поведение, которое было до этой миграции. Поэтому у миграции нет и бэкофилла: ни одному
-- существующему участнику ни одного проекта она ничего не меняет.
--
-- Отдельного индекса под «все наблюдатели проекта» (mode = 'ALL') здесь нет. Запрос
-- рассылки идёт по project_id и отбирает из UNIQUE-индекса (project_id, user_id) строки
-- одного проекта — а строк в этой таблице по определению не больше, чем участников,
-- поставивших настройку руками. Частичный индекс на такой выборке планировщик не выберет.
