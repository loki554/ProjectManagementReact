-- Спринты (4.9): именованный отрезок времени, внутри которого команда договорилась
-- сделать определённый набор задач. До сих пор в трекере был только один способ сказать
-- «это делаем сейчас» — статус задачи, но он про состояние одной задачи, а не про план на
-- две недели: по нему нельзя ни спросить «что мы обещали к пятнице», ни ответить «успели
-- ли», ни отложить недоделанное на следующий заход.
--
-- Майлстоун отдельной таблицей не заводится. Он отличается от спринта не полями (те же имя,
-- цель, окно дат и набор задач), а тем, что окно схлопывается в точку: у майлстоуна
-- start_date = end_date, и это единственная разница, которую видно в интерфейсе. Вторая
-- таблица с той же схемой, той же ссылкой из tasks и тем же экраном означала бы дубль
-- ради слова, а не ради данных; появятся у майлстоуна собственные поля — он и станет
-- собственной сущностью.
--
-- Связь с задачей — одиночная ссылка из tasks, а не таблица связей: задача принадлежит
-- одному спринту (в этом и смысл — «мы обещали её вот в этот заход»), и many-to-many здесь
-- означал бы задачу, посчитанную в прогрессе двух спринтов сразу.

CREATE TABLE sprints (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,

    -- Цель спринта — одна-две фразы «зачем мы его собрали». Не TEXT: это заголовок плана,
    -- а не описание задачи, и место для мегабайта здесь ни к чему.
    goal VARCHAR(2000),

    -- DATE, а не TIMESTAMPTZ. Спринт планируют днями («с понедельника по пятницу через
    -- две недели»), и точное время начала не значит ничего, зато часовой пояс превращает
    -- «до 30-го» у одного участника в «до 29-го» у другого. Ровно та же причина, по которой
    -- у задачи срок остаётся моментом времени (V7): там дедлайн — это «к 18:00», здесь
    -- граница — это день.
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,

    -- PLANNED / ACTIVE / COMPLETED. Статус хранится явно, а не выводится из дат: «спринт
    -- начался» — это решение команды, а не наступление календарной даты, и спринт вполне
    -- может стартовать на день позже или закрыться на два дня раньше. Вычисляемый из дат
    -- статус ещё и невозможно закрыть: незакрытый спринт прошлого месяца обязан оставаться
    -- видимым как незакрытый, а не превращаться в «завершён» сам собой.
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED',

    -- Когда реально начали и закрыли — момент времени, в отличие от плановых дат выше:
    -- это факт из журнала, а не строка плана.
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,

    created_by UUID NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Имя уникально в проекте: два «Спринт 12» в одном списке неразличимы, а ссылаются на
    -- спринт в разговоре именно именем.
    CONSTRAINT uq_sprints_project_name UNIQUE (project_id, name),

    -- Спринт, который заканчивается раньше, чем начался, — это опечатка в форме, и
    -- поймать её лучше на входе. Проверка дублирует явный отказ сервиса (400
    -- SPRINT_DATES_INVALID, чтобы человек увидел причину), но остаётся в схеме: сюда
    -- ходят и миграции, и psql.
    CONSTRAINT chk_sprints_dates CHECK (end_date >= start_date)
);

CREATE INDEX idx_sprints_project_id ON sprints(project_id);

-- Активный спринт в проекте ровно один. Это не косметика: «текущий спринт» — то, на что
-- ссылается вопрос «чем мы сейчас заняты», и два одновременно активных делают ответ на
-- него неопределённым. Частичный уникальный индекс, а не проверка в сервисе: сервис
-- отвечает внятным 409 SPRINT_ALREADY_ACTIVE, а индекс не даёт двум одновременным запросам
-- «начать спринт» проскочить мимо этой проверки в разных транзакциях.
CREATE UNIQUE INDEX uq_sprints_one_active ON sprints(project_id) WHERE status = 'ACTIVE';

-- ON DELETE SET NULL, как у категории (V18): удаление спринта не должно уносить задачи.
-- Задача, лишившаяся спринта, возвращается в бэклог — то есть остаётся ровно там, где была
-- до планирования.
ALTER TABLE tasks
    ADD COLUMN sprint_id UUID REFERENCES sprints(id) ON DELETE SET NULL;

-- Основной запрос — «задачи этого спринта» (страница спринтов и фильтр списка задач).
CREATE INDEX idx_tasks_sprint_id ON tasks(sprint_id);

-- Спринт становится ещё одним фильтром списка задач, значит его нужно уметь сохранять в
-- представлении (4.7). Пара «значение + флаг», как у категории: «без спринта» (бэклог) —
-- это выбранный пункт фильтра, а не отсутствие выбора, и выразить его пустым id нечем.
-- ON DELETE SET NULL по той же причине, что и у остальных ссылок saved_views: удалённый
-- спринт превращает фильтр в «любой спринт», а не в мёртвый UUID, по которому список молча
-- пустеет.
ALTER TABLE saved_views
    ADD COLUMN sprint_id UUID REFERENCES sprints(id) ON DELETE SET NULL;

ALTER TABLE saved_views
    ADD COLUMN no_sprint BOOLEAN NOT NULL DEFAULT FALSE;
