-- Столбец версии для оптимистичных блокировок (3.4).
--
-- До сих пор одновременное редактирование одной сущности заканчивалось тем, что побеждал
-- сохранивший последним: он записывал ВСЕ поля формы, включая те, что успел поменять
-- другой, и делал это молча — ни конфликта, ни следа в ленте активности. Для трекера, где
-- над задачей работают несколько человек, это прямая потеря данных.
--
-- Столбец ведёт Hibernate (@Version): при каждом UPDATE он добавляет в WHERE текущее
-- значение и увеличивает его; если строку успели обновить, UPDATE не находит строку и
-- транзакция падает вместо перезаписи.
--
-- Версия отдаётся клиенту в ответе и возвращается обратно в запросе на изменение — иначе
-- защита сработала бы только на пересечении двух запросов в пределах секунды, а
-- настоящий сценарий другой: две формы, открытые десять минут назад.
--
-- Три таблицы, а не все подряд: правят одновременно именно их. Особенно project_wiki —
-- там один большой текст на весь проект, и затирание чужой правки означает потерю
-- страницы целиком.
--
-- DEFAULT 0 нужен и для существующих строк, и для новых: INSERT'ы Hibernate версию
-- проставляет сам, но default избавляет от NOT NULL-нарушений при вставках мимо ORM
-- (миграции, ручные правки).

ALTER TABLE tasks ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE projects ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE project_wiki ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
