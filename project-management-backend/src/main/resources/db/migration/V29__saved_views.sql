-- Сохранённые представления списка задач (4.7): именованный набор фильтров и сортировки,
-- который человек заводит один раз и дальше открывает в один клик.
--
-- Хранится типизированными колонками, а не строкой запроса и не JSON'ом. Строку было бы
-- дешевле записать (фронтенд и так держит фильтры в URL), но представление живёт годами, а
-- ссылается на строки соседних таблиц: удалённый тэг в JSON'е остаётся мёртвым UUID, и
-- представление молча начинает показывать пустой список — без единой ошибки где-либо.
-- С колонкой и внешним ключом то же удаление превращает фильтр по тэгу в «любой тэг»
-- (ON DELETE SET NULL): представление расширяется, а не ломается. Цена — миграция на каждый
-- новый фильтр; в проекте, где их 29, это не та цена, ради которой стоит терять целостность.
--
-- Набор колонок повторяет параметры GET /api/projects/{id}/tasks один в один, включая пары
-- «значение + булев флаг» (assignee_id/unassigned, category_id/uncategorized): «без
-- исполнителя» — это выбранный пункт фильтра, а не отсутствие выбора, и выразить его пустым
-- id нечем. Приоритет флага над значением — тот же, что на проводе и в массовой правке (4.6).
--
-- Представление персональное (owner_id): «мои просроченные» у каждого свои, а общий на проект
-- именованный фильтр — это отдельный разговор про то, кто вправе его переименовать и что с
-- ним будет, когда автор уйдёт из проекта. Поделиться отфильтрованным списком можно ссылкой:
-- всё состояние фильтров теперь лежит в URL (5.5).

CREATE TABLE saved_views (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    -- ON DELETE CASCADE: представления удалённого пользователя не нужны никому — их не видел
    -- никто, кроме него самого.
    owner_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,

    search VARCHAR(200),
    -- Статус, срок и ключ сортировки — enum'ы приложения, а не строки справочников: внешнему
    -- ключу здесь не на что ссылаться. Значения проверяет DTO при сохранении, неизвестное до
    -- БД не доезжает.
    status VARCHAR(20),
    assignee_id UUID REFERENCES users(id) ON DELETE SET NULL,
    unassigned BOOLEAN NOT NULL DEFAULT FALSE,
    -- «Мои» задачи хранятся флагом, а не id владельца представления. Разница видна ровно
    -- тогда, когда представление уезжает по ссылке: assignee_id = <UUID автора> у коллеги
    -- покажет задачи автора, а флаг — его собственные, то есть то, что написано на кнопке.
    assigned_to_me BOOLEAN NOT NULL DEFAULT FALSE,
    tag_id UUID REFERENCES tags(id) ON DELETE SET NULL,
    category_id UUID REFERENCES categories(id) ON DELETE SET NULL,
    uncategorized BOOLEAN NOT NULL DEFAULT FALSE,
    due VARCHAR(20),

    sort VARCHAR(20) NOT NULL DEFAULT 'NUMBER',
    descending BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Имя уникально в пределах «мой список в этом проекте»: два «Мои просроченные» в одном
    -- ряду кнопок неразличимы, а у соседа своё такое же — и это нормально.
    CONSTRAINT uq_saved_views_owner_name UNIQUE (project_id, owner_id, name)
);

