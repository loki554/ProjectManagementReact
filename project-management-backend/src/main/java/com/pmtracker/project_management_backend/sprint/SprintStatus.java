package com.pmtracker.project_management_backend.sprint;

/**
 * Жизненный цикл спринта (4.9). Порядок констант — порядок жизненного цикла, как у
 * {@link com.pmtracker.project_management_backend.task.TaskStatus}: по нему сортируется
 * список спринтов и рисуются вкладки на странице.
 *
 * <p>Переходы односторонние: PLANNED → ACTIVE → COMPLETED. Обратного пути нет намеренно.
 * «Переоткрыть» завершённый спринт значит переписать факт: набор задач в нём уже разошёлся
 * по следующим заходам, а отчёт «что успели за этот» уже прочитан. Нужен ещё один заход —
 * это следующий спринт, и заводится он как следующий спринт.
 */
public enum SprintStatus {
    PLANNED,
    ACTIVE,
    COMPLETED
}
