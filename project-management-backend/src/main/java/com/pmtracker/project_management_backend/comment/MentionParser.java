package com.pmtracker.project_management_backend.comment;

import com.pmtracker.project_management_backend.common.UsernameNormalizer;

import java.util.LinkedHashSet;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Разбор @упоминаний в тексте комментария (4.5).
 * <p>
 * <b>Синтаксис — {@code @никнейм}</b> (см. {@code User.username}, V28). Разбирать упоминание
 * обязан <b>сервер</b>: список получателей уведомления — это права, и принимать его от
 * клиента отдельным полем значило бы дать любому участнику способ прислать уведомление кому
 * угодно, никого не упомянув в самом тексте. Значит, в тексте должно стоять что-то, что
 * сервер опознаёт сам, — уникальное, стабильное и с ясной границей в свободном тексте.
 * <p>
 * ФИО на эту роль не годятся: тёзки в одном проекте — вопрос времени, а границу
 * «@Иванов Иван Петрович» без словаря участников в тексте не найти. Первая версия брала
 * почтовый адрес — он уникален и разбирается, но это контактные данные, которым нечего
 * делать в тексте, видном всему проекту, и читать «@ivanov@example.com» посреди фразы
 * невозможно. Никнейм даёт ту же однозначность, ничего лишнего о человеке не сообщая.
 * <p>
 * Цена решения: смена никнейма (она разрешена, см. UserService.updateProfile) оставляет
 * старые упоминания в уже написанных комментариях текстом — они перестают подсвечиваться и
 * вести к человеку. Функционально при этом не теряется ничего: уведомление доставляется в
 * момент написания комментария, а не при каждом его прочтении. Чинилось бы это таблицей
 * упоминаний с id вместо текста — то есть вторым источником правды рядом с телом, которое
 * человек в любой момент правит; за подсветку старых упоминаний такая цена высока.
 */
final class MentionParser {

    /**
     * {@code @} плюс никнейм. Границы с обеих сторон нужны обе и по разным причинам.
     * <p>
     * Ретроспективный просмотр не даёт сработать внутри почтового адреса, написанного в тексте
     * без всякого упоминания: в «пишите на ivan@example.com» перед {@code @} стоит буква.
     * <p>
     * Просмотр вперёд отсекает слишком длинное: без него {@code @} и тридцать пять символов
     * подряд дали бы «упоминание» из первых тридцати — то есть чужой никнейм, собранный из
     * куска чужого слова. Точка в набор границы не входит, поэтому «зайдите к @ivanov.»
     * разбирается как {@code ivanov}, а не остаётся неразобранным.
     */
    private static final Pattern MENTION = Pattern.compile(
            "(?<![A-Za-z0-9_\\-@])@([A-Za-z0-9_\\-]{3,30})(?![A-Za-z0-9_\\-])");

    private MentionParser() {
    }

    /**
     * Никнеймы, упомянутые в тексте, в порядке появления и без повторов.
     * <p>
     * Нормализуются так же, как при регистрации ({@link UsernameNormalizer}): в базе никнейм
     * лежит в нижнем регистре, и {@code @Ivanov} обязан находить того же человека, что и
     * {@code @ivanov}, — иначе упоминание молча не срабатывало бы из-за заглавной буквы,
     * поставленной автозаменой в начале предложения.
     * <p>
     * Порядок появления сохраняется ({@code LinkedHashSet}) не для красоты: на нём стоит
     * ограничение числа получателей в {@code TaskCommentService} — отрезать надо хвост
     * списка, а не случайные элементы.
     */
    static Set<String> parse(String body) {
        if (body == null || body.isBlank()) {
            return Set.of();
        }
        Set<String> usernames = new LinkedHashSet<>();
        Matcher matcher = MENTION.matcher(body);
        while (matcher.find()) {
            usernames.add(UsernameNormalizer.normalize(matcher.group(1)));
        }
        return usernames;
    }
}
