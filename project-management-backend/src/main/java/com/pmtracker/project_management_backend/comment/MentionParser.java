package com.pmtracker.project_management_backend.comment;

import com.pmtracker.project_management_backend.common.EmailNormalizer;

import java.util.LinkedHashSet;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Разбор @упоминаний в тексте комментария (4.5).
 * <p>
 * <b>Синтаксис — {@code @почта}</b>, а не {@code @Фамилия Имя} и не разметка вида
 * {@code @[Иванов Иван](uuid)}. Причина не в красоте, а в том, что упоминание обязано
 * разбираться <b>на сервере</b>: список получателей уведомления — это права, и принимать
 * его от клиента отдельным полем значило бы дать любому участнику способ прислать
 * уведомление кому угодно, никого не упомянув в самом тексте.
 * <p>
 * Из того, что сервер может разобрать сам, годится только уникальный и стабильный
 * идентификатор. Имён у людей ровно столько, что тёзки в одном проекте — вопрос времени,
 * а границу «@Иванов Иван Петрович» без словаря участников в тексте не найти. Разметка со
 * скрытым id решала бы обе задачи, но её видно всем, кто читает комментарий не через наш
 * фронтенд, — в письме об уведомлении, в выдаче поиска, в API. Адрес же остаётся читаемым
 * везде: даже без единой строчки клиентского кода {@code @ivanov@example.com} — это
 * по-прежнему понятное обращение к человеку. Как это <i>выглядит</i>, решает уже слой
 * отображения: фронтенд рисует на месте адреса имя (см. {@code lib/mentions.js}).
 * <p>
 * Обратная сторона решения: смена адреса рвёт старые упоминания, а сам адрес участника
 * виден всем, кто читает тред. Второе в этом приложении не новость — почта участников и
 * так стоит в списке проекта, — а первое касается только уже отправленных уведомлений,
 * которые к тому моменту давно доставлены.
 */
final class MentionParser {

    /**
     * Адрес после {@code @}. Проверка нарочно грубая: тонко проверять синтаксис почты
     * здесь нечего — найденный адрес всё равно сверяется со списком участников проекта, и
     * всё, что не совпало со строкой в базе, отбрасывается. Единственное требование к
     * шаблону — не хватать лишнего из соседнего текста.
     * <p>
     * Отрицательный ретроспективный просмотр не даёт сработать внутри обычного адреса,
     * написанного в тексте без всякого упоминания: в «пишите на ivan@example.com» перед
     * {@code @} стоит буква, и это не упоминание домена example.com, а просто адрес.
     * По той же причине не годится и «@» в конце слова.
     */
    private static final Pattern MENTION = Pattern.compile(
            "(?<![A-Za-z0-9._%+\\-])@([A-Za-z0-9._%+\\-]+@[A-Za-z0-9.\\-]+\\.[A-Za-z]{2,})");

    private MentionParser() {
    }

    /**
     * Адреса, упомянутые в тексте, в порядке появления и без повторов.
     * <p>
     * Нормализуются так же, как при регистрации ({@link EmailNormalizer}): в базе адреса
     * лежат в нижнем регистре (V26), и {@code @Ivanov@Example.com} обязан находить того же
     * человека, что и {@code @ivanov@example.com}, — иначе упоминание молча не срабатывало
     * бы из-за регистра, набранного автозаменой на телефоне.
     * <p>
     * Порядок появления сохраняется ({@code LinkedHashSet}) не для красоты: на нём стоит
     * ограничение числа получателей в {@code TaskCommentService} — отрезать надо хвост
     * списка, а не случайные элементы.
     */
    static Set<String> parse(String body) {
        if (body == null || body.isBlank()) {
            return Set.of();
        }
        Set<String> emails = new LinkedHashSet<>();
        Matcher matcher = MENTION.matcher(body);
        while (matcher.find()) {
            emails.add(EmailNormalizer.normalize(matcher.group(1)));
        }
        return emails;
    }
}
