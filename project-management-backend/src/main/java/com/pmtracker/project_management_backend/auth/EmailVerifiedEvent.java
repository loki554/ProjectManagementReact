package com.pmtracker.project_management_backend.auth;

import java.util.UUID;

/**
 * «Этот пользователь только что доказал, что владеет своим почтовым ящиком».
 * <p>
 * Нужно это ровно одному потребителю — приглашениям в проект (4.2): приглашение выписано
 * на адрес, а не на аккаунт, и момент подтверждения адреса — единственный, когда мы точно
 * знаем, что за этим адресом стоит вот этот пользователь. Слушатель в пакете project
 * добавляет его во все проекты, куда его звали, пока аккаунта ещё не было.
 * <p>
 * Событие, а не прямой вызов, по двум причинам. Первая — направление зависимостей: пакет
 * project и так знает про auth (ему нужен User), обратная связь замкнула бы их в кольцо.
 * Вторая — приглашения не должны иметь права уронить подтверждение адреса: слушатель
 * работает после коммита и в своей транзакции, и что бы там ни случилось, email остаётся
 * подтверждённым, а человек — способным войти.
 * <p>
 * Публикуется только на переходе «не подтверждён → подтверждён», то есть не более одного
 * раза на пользователя; повторный переход по той же ссылке события не даёт (токен сгорел).
 */
