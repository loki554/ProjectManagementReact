package com.pmtracker.project_management_backend.report.dto;

import java.util.List;

/**
 * Дашборд проекта (4.11).
 *
 * <p>Четыре ответа на четыре разных вопроса: сколько всего работы и сколько её открыто
 * (счётчики), где она скопилась (распределение по статусам), на ком висит (распределение
 * по исполнителям), сколько времени проводит в каждом статусе (среднее) и успеваем ли мы
 * в текущий заход (burndown).
 *
 * <p><b>Что чем ограничено.</b> Первые четыре блока считаются по всему проекту и не зависят
 * от выбранного спринта: дашборд отвечает на вопрос «как дела у проекта», а не «как дела у
 * спринта» — на второй отвечает страница спринтов с её полосой прогресса. Спринт нужен
 * только burndown'у, потому что выгорание без отрезка времени не определено вовсе: нужно
 * знать, от какой даты до какой падает линия.
 */
public record DashboardResponse(
        long totalTasks,
        long openTasks,
        /** Все шесть статусов, включая пустые: отсутствие задач в статусе — тоже ответ. */
        List<StatusCountRow> statusDistribution,
        List<AssigneeLoadRow> assigneeDistribution,
        List<StatusDurationRow> averageTimeInStatus,
        /** null, если в проекте нет ни одного спринта, по которому можно построить линию. */
        BurndownResponse burndown
) {
}
