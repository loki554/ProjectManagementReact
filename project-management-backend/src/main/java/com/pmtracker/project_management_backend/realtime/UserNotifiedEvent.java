package com.pmtracker.project_management_backend.realtime;

import java.util.UUID;

/**
 * «Этому человеку появилось уведомление» (4.15). Второй и последний источник сообщений в
 * поток; публикуется в {@code NotificationService.create}.
 * <p>
 * Отдельно от {@link ProjectChangedEvent}, хотя почти всякое уведомление рождается из
 * какого-нибудь изменения в проекте, — потому что получатель другой. Изменение в проекте
 * идёт всем его участникам, у кого открыта вкладка; уведомление адресовано одному человеку
 * и больше никому. Свести их к одному событию значило бы либо рассылать чужой колокольчик
 * всему проекту, либо на каждое изменение проекта дёргать колокольчик у тех, кого оно не
 * касается.
 * <p>
 * Полей ровно столько, сколько нужно, чтобы клиент понял, что перечитывать, — про само
 * уведомление здесь ничего нет по той же причине, что и везде в 4.15
 * (см. {@link RealtimeMessage}): текст, автор и признак прочитанности приедут обычным
 * запросом за списком, с обычной проверкой прав.
 */
public record UserNotifiedEvent(UUID recipientId, String type, UUID projectId, UUID taskId, UUID actorId) {
}
