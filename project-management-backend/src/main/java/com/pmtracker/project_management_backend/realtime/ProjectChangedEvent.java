package com.pmtracker.project_management_backend.realtime;

import java.util.UUID;

/**
 * «В проекте что-то изменилось» — внутреннее событие приложения, из которого рождается
 * сообщение в открытый поток (4.15).
 * <p>
 * Публикуется ровно в одном месте — в {@code ActivityService.record}, то есть там же и
 * тогда же, когда изменение попадает в ленту активности. Это осознанный выбор
 * единственной точки вместо тридцати вызовов по доменным сервисам.
 * <p>
 * <b>Почему именно лента.</b> Живые обновления и лента активности отвечают на один и тот же
 * вопрос — «что только что произошло в этом проекте», — просто одна отвечает историей, а
 * другая уведомлением. Запись в ленту уже стоит в каждой правке, уже идёт в той же
 * транзакции (откат правки откатывает и запись), и уже несёт ровно те четыре поля, которые
 * нужны сигналу: проект, тип, задача, действующее лицо. Второй, параллельный набор вызовов
 * «а теперь ещё разошли событие» означал бы, что рано или поздно правка попадёт в ленту, но
 * не в поток, — и разъезд этот будет тихим.
 * <p>
 * <b>Чем за это плачено.</b> Живым становится ровно то, что пишется в ленту. Правки, которые
 * в неё сознательно не пишутся, потому что в истории проекта им не место — текст страницы
 * вики, тэги, категории, списанное время, галочки в чек-листе, — до чужого экрана сами не
 * доезжают и ждут обычного обновления по возвращении на вкладку. Обратное решение (свои
 * вызовы у каждой правки) стоило бы того самого молчаливого разъезда, и платить за вики
 * тэгами и категориями здесь дешевле, чем за всё сразу — надёжностью.
 */
public record ProjectChangedEvent(UUID projectId, String type, UUID taskId, UUID actorId) {
}
