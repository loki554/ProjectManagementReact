package com.pmtracker.project_management_backend.realtime;

import java.util.UUID;

/**
 * То, что уезжает в браузер по открытому потоку (4.15).
 * <p>
 * <b>Здесь нет данных — только адрес того, что изменилось.</b> Это главное решение всего
 * пункта, и оно не про экономию трафика.
 * <p>
 * Пушить в поток саму задачу выглядит очевидным улучшением: клиент подставит её в кэш, и
 * лишнего запроса не будет. Но у выгруженной задачи есть форма ({@code TaskResponse}) и
 * есть права: её нельзя показывать участнику, которого только что исключили; в ней
 * скрываются мягко удалённые подзадачи; поля вроде счётчика блокеров считаются запросами,
 * которые в момент рассылки уже вне транзакции. Пуш с данными — это второй путь чтения
 * доменного объекта, и он обязан повторить всё то же, что делает первый, при этом ходит он
 * не по запросу пользователя, а сам. Ошибка в нём выглядит не как 403, а как чужие данные
 * на экране.
 * <p>
 * Сигнал вместо данных снимает вопрос целиком. Клиент, получив «в проекте P изменилась
 * задача T», перезапрашивает ровно то, что у него открыто, — обычным авторизованным
 * запросом, через тот же контроллер и те же проверки, что и всегда. Худшее, что может
 * сделать сигнал, доставленный по ошибке (устаревшее членство, гонка при исключении из
 * проекта), — это спровоцировать запрос, на который сервер честно ответит 403.
 * <p>
 * Второе следствие: сигналу нечего протухать. Пуш с данными обязан приезжать в правильном
 * порядке и уметь не затирать более свежее состояние, только что полученное запросом, —
 * это версии, окна и вся сопутствующая арифметика. Сигнал же говорит «сходи посмотри», и
 * последним словом всегда остаётся ответ сервера.
 *
 * @param scope     {@code project} — что-то изменилось в проекте; {@code notification} —
 *                  у получателя появилось личное уведомление (колокольчик). Разделение не
 *                  косметическое: у этих двух разные получатели (участники проекта против
 *                  одного человека) и разная реакция на клиенте
 * @param type      код события — тот же, что у записи в ленте активности
 *                  ({@code task_created}, {@code comment_added}, {@code member_removed}…).
 *                  Клиенту он нужен ровно для того, чтобы отличить правку самого проекта
 *                  от правки его содержимого; всё остальное он инвалидирует одинаково
 * @param projectId проект, к которому относится событие; null у {@code notification}
 * @param taskId    задача, если событие про задачу
 * @param actorId   кто это сделал. Нужен, чтобы клиент мог не реагировать на собственные
 *                  действия: свою же правку он уже применил, не дожидаясь эха
 */
public record RealtimeMessage(String scope, String type, UUID projectId, UUID taskId, UUID actorId) {

    public static final String SCOPE_PROJECT = "project";
    public static final String SCOPE_NOTIFICATION = "notification";

    static RealtimeMessage project(UUID projectId, String type, UUID taskId, UUID actorId) {
        return new RealtimeMessage(SCOPE_PROJECT, type, projectId, taskId, actorId);
    }

    static RealtimeMessage notification(String type, UUID projectId, UUID taskId, UUID actorId) {
        return new RealtimeMessage(SCOPE_NOTIFICATION, type, projectId, taskId, actorId);
    }
}
