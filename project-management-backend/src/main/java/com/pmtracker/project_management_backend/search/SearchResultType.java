package com.pmtracker.project_management_backend.search;

/**
 * Что именно нашлось. Одновременно и тип результата в ответе, и необязательный фильтр
 * запроса (?type=TASK) — enum, а не строка, потому что значение попадает в состав
 * UNION-запроса, и набор обязан быть закрытым: неизвестное значение Spring отбивает 400
 * ещё до сервиса (тот же приём, что у TaskSortKey в 3.3).
 */
public enum SearchResultType {

    /** Название или описание задачи. */
    TASK,

    /** Тело комментария к задаче. */
    COMMENT,

    /** Страница вики проекта. */
    WIKI
}
