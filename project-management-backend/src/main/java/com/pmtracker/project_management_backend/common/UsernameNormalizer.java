package com.pmtracker.project_management_backend.common;

import java.util.Locale;

/**
 * Приведение никнейма к каноническому виду перед сравнением и записью.
 * <p>
 * Никнейм хранится и сравнивается в нижнем регистре — в отличие от почты, где регистр
 * приходится нормализовать задним числом (см. {@link EmailNormalizer} и V26), здесь он
 * просто не существует: {@code @Ivanov} и {@code @ivanov} обязаны быть одним человеком, а
 * второй смысл — «показывать так, как ввели» — никнейму не нужен, потому что рядом с ним
 * всегда стоит настоящее имя.
 * <p>
 * Регистр важнее, чем кажется: без нормализации автозамена на телефоне, ставящая заглавную
 * букву в начале предложения, превращала бы {@code @ivanov} в никого — упоминание молча не
 * срабатывало бы, и понять почему было бы нечем.
 * <p>
 * Утилита общая, а не приватный метод, ровно по той же причине, что и у почты: путей записи
 * два (регистрация и профиль), плюс разбор упоминаний, и разъезд между ними и был бы ошибкой.
 */
public final class UsernameNormalizer {

    /**
     * Формат никнейма. Дублируется в трёх местах — здесь, в {@code @Pattern} на DTO и в
     * CHECK-ограничении V28, — и это не оплошность: DTO даёт человеку внятную ошибку 400,
     * БД удерживает инвариант независимо от того, какой код в неё пишет, а константа здесь
     * держит их согласованными и служит одним местом, где формат описан словами.
     * <p>
     * Точки в наборе нет намеренно: упоминание в тексте кончается на первом символе не из
     * набора, и без точки «зайдите к @ivanov.» разбирается однозначно.
     */
    public static final String PATTERN = "^[a-z0-9_-]{3,30}$";

    /**
     * Тот же формат, но с заглавными буквами — для {@code @Pattern} на DTO.
     * <p>
     * Отдельная константа нужна из-за порядка: Bean Validation отрабатывает до тела метода,
     * то есть до нормализации, и с канонической маской человек, набравший «Ivanov», получал
     * бы 400 вместо никнейма «ivanov». Регистр здесь не ошибка ввода, а то, что мы и так
     * умеем приводить, — ровно как с почтой ({@code Ivan@Company.com} принимается).
     */
    public static final String INPUT_PATTERN = "^[A-Za-z0-9_-]{3,30}$";

    public static final int MAX_LENGTH = 30;

    private UsernameNormalizer() {
    }

    /**
     * @param username как его прислал клиент; {@code null} пропускается насквозь — обязательность
     *                 поля обеспечивают {@code @NotBlank}/{@code @Pattern} на DTO
     */
    public static String normalize(String username) {
        return username == null ? null : username.trim().toLowerCase(Locale.ROOT);
    }
}
