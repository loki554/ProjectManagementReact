package com.pmtracker.project_management_backend.common;

import java.util.Locale;

/**
 * Приведение почтового адреса к каноническому виду перед сравнением и записью.
 * <p>
 * Домен регистронезависим по RFC 5321, а локальную часть все живые почтовые провайдеры
 * тоже считают регистронезависимой, поэтому {@code Ivan@Company.com} и
 * {@code ivan@company.com} — один и тот же ящик и обязаны быть одним и тем же аккаунтом.
 * Без нормализации уникальный индекс по {@code users.email} их не склеивает: получаются
 * две учётные записи на один ящик, вход «не тем регистром» отвечает «неверный пароль»,
 * а письмо о сбросе уходит в ту из них, которую человек не заводил.
 * <p>
 * Утилита общая, а не приватный метод в каждом сервисе, именно потому, что расхождение
 * здесь и было ошибкой: приглашения (ProjectInvitationService) хранили адрес в нижнем
 * регистре, а регистрация — как прислал клиент, и поиск существующего пользователя по
 * сырому адресу промахивался мимо собственной же записи.
 */
public final class EmailNormalizer {

    private EmailNormalizer() {
    }

    /**
     * @param email адрес как его прислал клиент; {@code null} пропускается насквозь,
     *              чтобы вызывающему не приходилось дублировать проверку — обязательность
     *              поля обеспечивают {@code @NotBlank}/{@code @Email} на DTO.
     */
    public static String normalize(String email) {
        return email == null ? null : email.trim().toLowerCase(Locale.ROOT);
    }
}
