package com.pmtracker.project_management_backend.common.scheduling;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * Взаимное исключение для заданий по расписанию между инстансами приложения (3.8).
 * <p>
 * {@code @Scheduled} срабатывает на каждом инстансе — это его нормальное поведение, а не
 * недосмотр. Для идемпотентных уборок (токены, корзина, файлы-сироты) это безобидно: второй
 * инстанс удалит ноль строк. Но задание, которое что-то СОЗДАЁТ, так себя вести не может:
 * два одновременных скана дедлайнов приходят к одному и тому же выводу и шлют человеку два
 * одинаковых письма. Дедупликация в NotificationService спасает не полностью — она сама
 * читает-и-пишет, то есть проигрывает гонке ровно тогда, когда сканы идут параллельно.
 * <p>
 * Взята advisory-блокировка Postgres, а не ShedLock: библиотека принесла бы свою таблицу,
 * свою миграцию и свою модель «истёкшей» блокировки, тогда как нужен один вызов к БД,
 * которая уже есть и уже общая для всех инстансов.
 * <p>
 * Именно {@code _xact_}-вариант: такая блокировка снимается вместе с транзакцией — и на
 * коммите, и на откате, и при обрыве соединения, когда инстанс упал посреди работы.
 * Сессионный аналог пришлось бы освобождать руками и он бы навсегда завис после падения.
 */
@Component
public class SchedulerLock {

    private final JdbcTemplate jdbcTemplate;

    public SchedulerLock(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    /**
     * Пытается захватить блокировку на текущую транзакцию, не дожидаясь освобождения.
     *
     * <p>Именно try, а не ожидание: если задание уже выполняется где-то ещё, второму
     * инстансу нужно не встать в очередь и повторить работу через минуту, а просто
     * пропустить тик — следующий всё равно наступит.
     *
     * <p>ВЫЗЫВАТЬ ТОЛЬКО ВНУТРИ ТРАНЗАКЦИИ. Без неё каждый statement сам себе транзакция,
     * блокировка снимется на той же строке, где была взята, и метод будет всегда возвращать
     * true, ничего при этом не защищая.
     *
     * @return true — блокировка наша и работу можно делать; false — её держит кто-то другой
     */
    public boolean tryAcquire(SchedulerLockKey key) {
        return Boolean.TRUE.equals(
                jdbcTemplate.queryForObject("SELECT pg_try_advisory_xact_lock(?)", Boolean.class, key.value()));
    }
}
