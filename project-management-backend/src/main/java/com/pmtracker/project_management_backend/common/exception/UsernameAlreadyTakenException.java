package com.pmtracker.project_management_backend.common.exception;

/**
 * Никнейм занят. В отличие от занятого почтового адреса, о котором регистрация молчит
 * (см. {@code AuthService.register}: там ответ одинаков в обоих случаях, а владельцу ящика
 * уходит письмо), про никнейм сказать <b>нужно</b>, и это не противоречие.
 * <p>
 * Занятая почта — это факт о человеке: «у такого-то есть здесь аккаунт». Занятый никнейм —
 * факт о строке в публичном пространстве имён, ровно как занятое имя проекта; узнать его
 * можно, просто открыв список участников любого общего проекта. Молчать о нём нельзя ещё и
 * практически: человек не сможет зарегистрироваться, пока не выберет свободный, и «попробуйте
 * что-нибудь другое, но что именно — не скажем» это не защита, а неработающая форма.
 */
public class UsernameAlreadyTakenException extends RuntimeException {

    public UsernameAlreadyTakenException() {
        super("This username is already taken");
    }
}
