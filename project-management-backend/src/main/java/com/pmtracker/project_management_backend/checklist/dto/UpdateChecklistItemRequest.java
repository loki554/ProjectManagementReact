package com.pmtracker.project_management_backend.checklist.dto;

import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

/**
 * Правка пункта чек-листа: текст, галочка или и то и другое.
 *
 * <p>Единственный частичный (null = «не трогать») запрос среди правок в трекере, и это
 * осознанное исключение. Везде ещё форма приезжает целиком, потому что везде ещё её
 * действительно заполняют целиком. Здесь два действия физически разные: галочку ставят одним
 * кликом по строке, текст правят, открыв её на редактирование. Полная замена означала бы,
 * что клик по галочке присылает обратно и текст — то есть затирает правку, сохранённую в
 * соседней вкладке, ничего при этом не меняя по своей воле.
 *
 * <p>Пустой текст — не «стереть пункт», а ошибка запроса: пункт без текста нельзя ни
 * показать, ни отметить. Стирают пункт удалением, у которого есть свой метод.
 *
 * <p>Версии (3.4) у пункта нет по той же причине, по которой её нет у комментария: спорить
 * здесь не о чем — конкурентная правка либо ставит ту же галочку, либо переписывает строку,
 * которую видно целиком.
 */
public record UpdateChecklistItemRequest(
        // (?s) — чтобы точка покрывала и перевод строки: пункт в пятьсот символов вполне
        // может оказаться с переносом, и отклонять его из-за этого незачем.
        @Size(max = 500) @Pattern(regexp = "(?s).*\\S.*", message = "must not be blank") String content,
        Boolean done
) {
}
