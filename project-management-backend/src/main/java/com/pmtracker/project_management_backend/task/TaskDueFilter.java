package com.pmtracker.project_management_backend.task;

import java.time.Duration;

/**
 * Фильтр списка задач по сроку (4.7). Появился ради сохранённых представлений: «мои
 * просроченные» и «горит на этой неделе» — это те же фильтры, что и раньше, плюс окно
 * дедлайна, и без него оба сводились бы к сортировке по сроку и разглядыванию глазами.
 *
 * <p>Окно отсчитывается от «сейчас», а не от границ календарных суток. Календарные границы
 * потребовали бы часового пояса читателя: {@code due_date} хранится в TIMESTAMPTZ, «сегодня»
 * у человека в Калининграде и у человека во Владивостоке — разные отрезки, и сервер, ничего
 * о них не зная, отвечал бы по UTC, то есть никому. Скользящее окно от текущего момента
 * одинаково честно для всех: «в ближайшие сутки», «в ближайшую неделю».
 *
 * <p>Окна вложены: уже просроченное входит и в {@link #TODAY}, и в {@link #WEEK}. Задача,
 * срок которой прошёл вчера, горит на этой неделе сильнее всех остальных, и прятать её из
 * списка, который человек открыл именно чтобы разобрать горящее, было бы ровно наоборот.
 *
 * <p>Выполненные и отклонённые задачи не попадают ни в одно окно: у них просроченный срок
 * уже ничего не значит (тот же {@code INACTIVE_STATUSES}, по которому не шлются напоминания
 * и не краснеет дата в таблице). Исключение — {@link #NONE}: «без срока» это утверждение о
 * пустом поле, а не о том, что задача чего-то требует.
 */
public enum TaskDueFilter {

    /** Срок прошёл. Нулевое окно — то есть «раньше, чем сейчас». */
    OVERDUE(Duration.ZERO),

    /** Срок в ближайшие сутки или уже прошёл. */
    TODAY(Duration.ofDays(1)),

    /** Срок в ближайшие семь дней или уже прошёл — «горит на этой неделе». */
    WEEK(Duration.ofDays(7)),

    /** Срок не проставлен вовсе. */
    NONE(null);

    private final Duration window;

    TaskDueFilter(Duration window) {
        this.window = window;
    }

    /**
     * Насколько вперёд от «сейчас» смотрит фильтр; {@code null} у {@link #NONE}, у которого
     * нет ни границы, ни условия на статус.
     */
    Duration window() {
        return window;
    }
}
