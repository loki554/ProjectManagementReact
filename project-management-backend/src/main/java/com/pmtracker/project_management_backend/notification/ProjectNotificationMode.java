package com.pmtracker.project_management_backend.notification;

/**
 * Насколько плотно человек хочет знать о происходящем в конкретном проекте (4.16).
 * <p>
 * Это вторая ось настройки уведомлений, поперечная первой. {@link NotificationSettings}
 * (4.3) отвечает на вопрос «как вам писать» — почтой или нет, сразу или сводкой, о каких
 * типах событий. Здесь — на вопрос «о чём», и задаётся он именно проектами: в одном
 * человек работает каждый день, во втором числится наблюдателем ради страницы вики, в
 * третий его позвали посмотреть один раз. Глобальными переключателями типов это не
 * выражается вовсе: выключить «комментарий к моей задаче» ради третьего проекта значит
 * выключить его и в первом.
 * <p>
 * Три значения, а не флаг «слежу / не слежу», потому что состояний по факту три: сверх
 * своего, своё и ничего. Свести их к двум можно только выкинув одно из осмысленных —
 * а выкидывать пришлось бы либо «я в этом проекте ведущий и хочу видеть всё», либо
 * «я здесь числюсь и не хочу видеть ничего».
 */
public enum ProjectNotificationMode {

    /**
     * Всё, что происходит в проекте: новые задачи и все комментарии, а не только те, что
     * касаются получателя лично. Плюс, разумеется, всё из {@link #PARTICIPATING}.
     */
    ALL,

    /**
     * Только то, что адресовано лично: назначили задачу, прокомментировали мою задачу,
     * упомянули по имени, горит срок моей задачи.
     * <p>
     * Значение по умолчанию и поведение приложения до 4.16 — поэтому отсутствие строки в
     * {@code project_notification_settings} означает именно его, и вступление в проект
     * никакой строки не создаёт (см. V35).
     */
    PARTICIPATING,

    /**
     * Ничего: ни письма, ни записи в колокольчике.
     * <p>
     * Именно ничего, включая назначение задачи и упоминание по имени, — и это осознанно.
     * Если бы «выключено» оставляло себе исключения, оно бы ничем не отличалось от
     * {@link #PARTICIPATING}, потому что PARTICIPATING ровно из этих исключений и состоит.
     * Работа при этом никуда не девается: задача из выключенного проекта по-прежнему стоит
     * в «моих задачах» и в списке задач проекта — выключается шум, а не сама задача.
     */
    MUTED
}
