package com.pmtracker.project_management_backend.notification;

/**
 * Как доставлять уведомления почтой (4.3).
 * <p>
 * Режим один на все типы, а не свой у каждого: «назначения мгновенно, комментарии дайджестом»
 * звучит гибко, но на практике означает несколько писем в день вместо одного и настройку,
 * в которой никто не разбирается. Выбор здесь между «знать сразу» и «не отвлекаться», и он
 * один для человека, а не для типа события.
 * <p>
 * Enum, а не строка — в отличие от {@code Notification.type}: типов уведомлений со временем
 * станет больше (упоминания, 4.5), и добавлять их без миграции удобно, а режимов доставки
 * ровно столько, сколько написано кода, который их обрабатывает.
 */
public enum NotificationDeliveryMode {

    /** Письмо на каждое событие, сразу после коммита создавшей его транзакции. */
    INSTANT,

    /** Одно письмо в сутки со сводкой накопившегося — см. {@code NotificationDigestJob}. */
    DAILY_DIGEST
}
