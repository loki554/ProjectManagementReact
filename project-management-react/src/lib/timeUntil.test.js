import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { msUntil } from './timeUntil'

// Часы подменены: функция считает разницу с Date.now(), а тест на «примерно столько же»
// был бы ровно тем flaky-тестом, который потом отключают.
const NOW = new Date('2026-08-26T12:00:00.000Z')

beforeEach(() => {
  vi.useFakeTimers()
  vi.setSystemTime(NOW)
})

afterEach(() => {
  vi.useRealTimers()
})

describe('msUntil', () => {
  it('до будущего срока — положительное число миллисекунд', () => {
    expect(msUntil('2026-08-26T14:30:00.000Z')).toBe(2.5 * 60 * 60 * 1000)
  })

  it('до прошедшего срока — отрицательное: просрочка измеряется тем же числом', () => {
    expect(msUntil('2026-08-25T12:00:00.000Z')).toBe(-24 * 60 * 60 * 1000)
  })

  it('ровно сейчас — ноль', () => {
    expect(msUntil(NOW.toISOString())).toBe(0)
  })

  // Разница считается по времени, а не по календарным датам, и это осознанно: в последние
  // сутки интерфейс переходит на часовой отсчёт, и «завтра» через 10 минут после полуночи
  // означало бы совсем не то, что показано пользователю.
  it('считает реальную разницу во времени, а не разницу дат', () => {
    expect(msUntil('2026-08-27T00:10:00.000Z')).toBe((12 * 60 + 10) * 60 * 1000)
  })
})
