import { create } from 'zustand'

/**
 * Жив ли сейчас поток живых обновлений (4.15).
 *
 * Стор, а не локальное состояние хука, потому что читателей у этого флага двое и они в
 * разных местах дерева: сам поток его пишет (см. useRealtimeUpdates), а запросы, у которых
 * есть периодический опрос, читают — чтобы опрашивать реже, пока поток работает
 * (см. notificationsQueries).
 *
 * Значение по умолчанию false, а не true: пока не доказано обратное, живых обновлений нет.
 * Ошибиться здесь можно в две стороны, и цена у них разная — лишний опрос раз в полминуты
 * против колокольчика, который молчит, потому что все уверены, что его обновит кто-то другой.
 */
export const useRealtimeStore = create((set) => ({
  connected: false,
  setConnected: (connected) => set({ connected }),
}))
