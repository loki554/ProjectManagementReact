#!/usr/bin/env bash
# Проверка дампа восстановлением: развернуть его во временную базу и убедиться, что там
# действительно наши данные, а не пустая схема. Вызывается из backup.sh сразу после
# снятия; можно позвать руками для любого файла:
#   docker compose ... exec backup bash /ops/verify-restore.sh /backups/pmtracker-….dump
#
# 8.5 IMPROVEMENTS.md.
set -euo pipefail

dump=${1:?укажите файл дампа}
scratch="verify_$(date -u +%H%M%S)_$$"

log() { echo "[verify $(date -u +%H:%M:%SZ)] $*"; }

# Временная база убирается при любом выходе, включая ошибку и Ctrl+C: иначе неудачная
# проверка оставляет за собой мусорную базу, и следующая падает уже на нехватке места.
cleanup() { dropdb --if-exists "$scratch" >/dev/null 2>&1 || true; }
trap cleanup EXIT

log "восстанавливаю $(basename "$dump") во временную базу $scratch"
createdb "$scratch"

# --exit-on-error обязателен: без него pg_restore честно печатает ошибки, но завершается
# с нулевым кодом, и «проверка» превращается в запуск, который всегда зелёный.
pg_restore --dbname="$scratch" --exit-on-error --no-owner --no-privileges "$dump"

# Проверяем не «база создалась», а что в ней есть то, ради чего всё делалось. Три вопроса,
# и каждый ловит свой класс поломки:
#   1) применённые миграции Flyway — восстановилась именно наша схема, а не чужая/пустая;
#   2) число таблиц — pg_restore не оборвался на середине;
#   3) есть хотя бы один пользователь — восстановились ДАННЫЕ, а не только структура
#      (дамп со схемой без строк выглядит совершенно здоровым, пока в него не заглянуть).
# "|| echo 0" здесь не прячет ошибку, а превращает её в ответ на заданный вопрос: при
# set -e упавший psql убил бы скрипт прямо здесь, и в логе осталось бы сырое
# «relation "flyway_schema_history" does not exist» вместо внятного вердикта ниже.
# Отсутствующая таблица — это и есть «миграций ноль», то есть ровно тот случай, ради
# которого проверка написана (поймано на обрезанном дампе).
q() { psql -d "$scratch" -tAc "$1" 2>/dev/null || echo 0; }

migrations=$(q "select count(*) from flyway_schema_history where success")
tables=$(q "select count(*) from information_schema.tables where table_schema='public'")
users=$(q "select count(*) from users")

log "миграций: $migrations, таблиц: $tables, пользователей: $users"

if [ "$migrations" -lt 1 ] || [ "$tables" -lt 10 ]; then
  log "ПРОВЕРКА НЕ ПРОЙДЕНА: дамп восстановился, но схема в нём неполная"
  exit 1
fi

# Пустая таблица пользователей — это не повод считать бэкап битым (так выглядит свежий
# стенд), но это ровно тот случай, который стоит увидеть в логе, а не узнать при аварии.
if [ "$users" -lt 1 ]; then
  log "ВНИМАНИЕ: в восстановленной базе нет ни одного пользователя — проверьте, тот ли это стенд"
fi

log "дамп восстанавливается, проверка пройдена"
