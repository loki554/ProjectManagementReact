#!/usr/bin/env bash
# Точка входа контейнера бэкапов: ждёт наступления BACKUP_AT и запускает backup.sh.
# 8.5 IMPROVEMENTS.md.
#
# Почему цикл на shell, а не cron: в образе postgres нет ни cron, ни crond, и ставить
# его apt'ом ради одной задачи в сутки — это лишний демон, лишний слой и лишний способ
# перепутать окружение (cron не наследует переменные контейнера, и PGPASSWORD пришлось бы
# прокидывать отдельным файлом). Цикл ниже делает ровно то же и виден целиком.
set -euo pipefail

BACKUP_AT=${BACKUP_AT:-03:30}

log() { echo "[scheduler $(date -u +%H:%M:%SZ)] $*"; }

log "расписание: ежедневно в $BACKUP_AT (TZ=${TZ:-UTC}), каталог ${BACKUP_DIR:-/backups}"

# Первый запуск — сразу, не дожидаясь ночи. Иначе ошибка в конфигурации (неверный пароль,
# нет прав на каталог) обнаружится только через сутки, причём ночью и без свидетелей.
log "стартовый прогон, чтобы конфигурация проверилась сейчас, а не через сутки"
bash /ops/backup.sh || log "СТАРТОВЫЙ ПРОГОН УПАЛ — расписание всё равно включаю, см. ошибку выше"

while true; do
  now=$(date +%s)
  # date -d принимает "HH:MM" как сегодняшнее время; если оно уже прошло — берём завтра.
  next=$(date -d "$BACKUP_AT" +%s)
  if [ "$next" -le "$now" ]; then
    next=$(date -d "tomorrow $BACKUP_AT" +%s)
  fi
  sleep_for=$((next - now))
  log "следующий запуск через $((sleep_for / 3600))ч $((sleep_for % 3600 / 60))м"
  sleep "$sleep_for"

  # Ошибка одного прогона не должна убивать контейнер: упавший бэкап — это повод
  # разобраться, а не повод не пробовать завтра. Поэтому || log, а не set -e насквозь.
  bash /ops/backup.sh || log "ПРОГОН УПАЛ, см. ошибку выше; следующая попытка по расписанию"
done
