#!/usr/bin/env bash
# Один цикл бэкапа: снять дамп, проверить его восстановлением, удалить просроченные.
# Запускается из scheduler.sh по расписанию; отдельным файлом — чтобы то же самое можно
# было выполнить руками: docker compose ... exec backup bash /ops/backup.sh
#
# 8.5 IMPROVEMENTS.md.
set -euo pipefail

BACKUP_DIR=${BACKUP_DIR:-/backups}
RETENTION_DAYS=${BACKUP_RETENTION_DAYS:-14}
VERIFY=${BACKUP_VERIFY:-true}

stamp=$(date -u +%Y%m%dT%H%M%SZ)
target="$BACKUP_DIR/${PGDATABASE}-${stamp}.dump"
tmp="$target.partial"

log() { echo "[backup $(date -u +%H:%M:%SZ)] $*"; }

mkdir -p "$BACKUP_DIR"

# --- снятие ---------------------------------------------------------------------------
# Формат custom (-Fc), а не простой SQL: он сжат, и его умеет pg_restore — то есть можно
# восстановить одну таблицу, посмотреть оглавление (pg_restore -l) и не разбирать
# мегабайты текста глазами. Плоский .sql годится ровно для одного сценария —
# «залить всё целиком в пустую базу», а это как раз тот сценарий, в котором что-то уже
# пошло не так и выбор хочется иметь.
#
# Пишем в .partial и переименовываем в конце: если контейнер убьют посреди дампа, в
# каталоге останется файл с расширением .partial, а не обрезанный .dump, который
# выглядит как полноценный бэкап ровно до того дня, когда его попробуют восстановить.
log "дамп ${PGDATABASE} -> $(basename "$target")"
pg_dump --format=custom --compress=6 --file="$tmp"
mv "$tmp" "$target"
log "готово, $(du -h "$target" | cut -f1)"

# --- проверка -------------------------------------------------------------------------
# «Бэкап, который ни разу не восстанавливали, бэкапом не является» — формулировка самого
# пункта, и это не фигура речи: молча испортиться может что угодно (место на диске,
# права, версия pg_dump новее сервера), а узнать об этом в день аварии — значит не узнать
# вовремя. Поэтому восстановление идёт сразу после снятия, в отдельную временную базу.
if [ "$VERIFY" = "true" ]; then
  bash /ops/verify-restore.sh "$target"
else
  log "ВНИМАНИЕ: проверка восстановлением выключена (BACKUP_VERIFY=$VERIFY)"
fi

# --- ротация --------------------------------------------------------------------------
# Чистим только после успешной проверки: если проверка упала, старые дампы — это всё,
# что у нас есть, и удалять их в этот момент решительно нечего.
#
# -mtime +N у find считает в сутках по 24 часа и отбрасывает остаток, поэтому "+$RETENTION_DAYS"
# удаляет файлы старше RETENTION_DAYS полных суток — то есть ровно N дневных дампов остаётся.
deleted=$(find "$BACKUP_DIR" -maxdepth 1 -name "${PGDATABASE}-*.dump" -mtime "+$RETENTION_DAYS" -print -delete | wc -l)
log "ротация: удалено просроченных дампов (старше ${RETENTION_DAYS} сут): $deleted"

# Заодно подбираем мусор от прерванных запусков — иначе .partial копятся вечно и
# однажды занимают весь том, из-за чего перестанут сниматься и нормальные дампы.
find "$BACKUP_DIR" -maxdepth 1 -name '*.partial' -mtime +1 -delete

log "в каталоге дампов: $(find "$BACKUP_DIR" -maxdepth 1 -name "${PGDATABASE}-*.dump" | wc -l), занято $(du -sh "$BACKUP_DIR" | cut -f1)"
